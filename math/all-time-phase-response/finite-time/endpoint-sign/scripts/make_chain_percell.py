"""Generate scripts/chain_percell.py from the committed absorption-b003/absorb_chain.py by four exact textual
patches, each required to apply exactly once. Nothing in the recursion changes:
  1. paths: constants.py, the lattice log and the default inputs are taken from finite-time/ (two levels up);
  2. logging condition: every cell instead of every 50th cell;
  3. log entries: exact decimal strings of the upper endpoints instead of nearest binary64 floats;
  4. the terminal table printer: prints only every 50th row and converts the strings for display.
Run from anywhere:  python3 -I make_chain_percell.py
"""
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
FT = HERE.parent.parent
SRC = FT / 'absorption-b003' / 'absorb_chain.py'
PIN = '0984e22cceb823e94811aea2eb80406854f34ab347a206d74973dc39c4bfc516'   # sha256 of absorption-b003/absorb_chain.py at f4fe230
text = SRC.read_text()
src_sha = hashlib.sha256(text.encode()).hexdigest()
if src_sha != PIN:
    raise SystemExit('absorb_chain.py does not match the pinned source')

patches = [
    ("spec = importlib.util.spec_from_file_location('constants', HERE.parent / 'constants.py')",
     "FT = HERE.parent.parent\nspec = importlib.util.spec_from_file_location('constants', FT / 'constants.py')"),
    ("constants.agmon_constant(HERE.parent)", "constants.agmon_constant(FT)"),
    ("ap.add_argument('--json', type=Path, default=HERE / 'results' / 'chain.json')",
     "ap.add_argument('--json', type=Path, required=True)"),
    ("ap.add_argument('--numerics', type=Path, default=HERE / 'results' / 'validated.json')",
     "ap.add_argument('--numerics', type=Path, default=FT / 'absorption-b003' / 'results' / 'validated.json')"),
    ("        if (j + 1) % 50 == 0 or j == n - 1:\n            log.append((float(tr.hi), float(m1.hi), float(m2.hi), float(epsW.hi), float(eps0.hi), float(eps1.hi), float(delta2.hi),\n                        float(S1cell.hi), float(sigma1.hi), float(Nw_tot.hi), float(Kw2.sqrt().hi)))",
     "        if True:\n            log.append((str(tr.hi), str(m1.hi), str(m2.hi), str(epsW.hi), str(eps0.hi), str(eps1.hi), str(delta2.hi),\n                        str(S1cell.hi), str(sigma1.hi), str(Nw_tot.hi), str(Kw2.sqrt().hi)))"),
    ("    for row in log:\n        print(f'{row[0]:6.3f}",
     "    for row in (tuple(float(x) for x in r) for k, r in enumerate(log) if (k + 1) % 50 == 0):\n        print(f'{row[0]:6.3f}"),
]
for old, new in patches:
    count = text.count(old)
    if count != 1:
        raise SystemExit(f'patch does not apply exactly once ({count}): {old[:70]!r}')
    text = text.replace(old, new)
header = (f'# GENERATED by make_chain_percell.py from absorption-b003/absorb_chain.py (sha256 {src_sha}).\n'
          f'# Do not edit; regenerate. The recursion is unchanged; see the generator docstring for the four patches.\n')
out = HERE / 'chain_percell.py'
if out.exists() and out.read_text() != header + text:
    raise SystemExit('chain_percell.py exists with different content; refusing to overwrite')
out.write_text(header + text)
print('source sha256', src_sha)
print('wrote', out, 'sha256', hashlib.sha256((header + text).encode()).hexdigest())
